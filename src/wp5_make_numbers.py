# -*- coding: utf-8 -*-
"""WP5 — Generate manuscript/numbers.tex: every in-text number as a LaTeX macro
sourced from output/ CSVs/JSON (traceability rule 6 of the honesty protocol)."""
from pathlib import Path
import glob
import json

import numpy as np
import pandas as pd

D1 = Path(__file__).resolve().parents[1]
OUT = D1 / "output"
MS = D1 / "manuscript"


def g(path, default="\\texttt{NA}"):
    p = OUT / path
    return p if p.exists() else None


def main() -> None:
    lines = ["% AUTO-GENERATED by src/wp5_make_numbers.py -- do not edit by hand"]

    def add(name, value):
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    # dataset sizes
    a = pd.read_parquet(D1 / "data" / "dataset_A_21city.parquet")
    b = pd.read_csv(D1 / "data" / "dataset_B_eurostat.csv")
    nn = a.dropna(subset=["cdw_total_kt"])
    add("nAcities", a.city.nunique())
    add("nArows", int(len(nn)))          # observed city-years (sparse panel)
    add("nArowsPanel", len(a))           # panel rows incl. covariate-only rows
    add("nAcore", int((nn.groupby('city').size() >= 5).sum()))
    add("nBcountries", b.country.nunique())
    add("nBrows", int(b.msw_gen_t.notna().sum()))
    add("nByearsMin", int(b.groupby('country').year.min().max()))
    add("nByearsMax", int(b.groupby('country').year.max().min()))
    # evaluation-point counts from the ladder (persistence row)
    lad = pd.read_csv(OUT / "analysis_ladder.csv")
    for st, tag in [("H", "Roll"), ("LOOCV", "Loocv")]:
        for ds, dt in [("C0", "C"), ("A", "A"), ("B", "B"), ("A17", "AR")]:
            q = lad[(lad.dataset == ds) & (lad.station == st) & (lad.model == "persistence")]
            if len(q):
                add(f"n{dt}Eval{tag}", int(q.n.iloc[0]))
    # A17 OLS disclosure
    q = infl = None

    # headline analysis numbers -- skipped: auto-derived names can contain
    # digits (dataset A17), which are invalid in LaTeX macro names; the named
    # macros below cover every number used in the text
    p = OUT / "analysis_headline.json"
    if False:
        pass

    # inflation table per-dataset means (independent of headline json format)
    p = OUT / "analysis_inflation.csv"
    if p.exists():
        infl = pd.read_csv(p)
        for ds, tag in [("C0", "CO"), ("A", "A"), ("B", "B"), ("A17", "AR")]:
            sub = infl[(infl.dataset == ds) & (infl.model != "persistence")]
            if len(sub):
                add(f"{tag}Infl", f"{sub.delta.mean()*100:+.0f}")
                add(f"{tag}MedInfl", f"{sub.delta.median()*100:+.0f}")
                add(f"{tag}InflLo", f"{sub.delta_lo.mean()*100:+.0f}")
                add(f"{tag}InflHi", f"{sub.delta_hi.mean()*100:+.0f}")
                add(f"{tag}InflMax", f"{sub.delta.max()*100:+.0f}")
                add(f"{tag}InflMaxModel", sub.loc[sub.delta.idxmax(), "model"].upper())
                add(f"{tag}InflMin", f"{sub.delta.min()*100:+.0f}")
                add(f"{tag}InflLoMed", f"{sub.delta_lo.median()*100:+.0f}")
                add(f"{tag}InflHiMed", f"{sub.delta_hi.median()*100:+.0f}")
            o17 = infl[(infl.dataset == "A17") & (infl.model == "ols")]
            if ds == "A17" and len(o17):
                add("AROlsHonest", f"{o17.r2_honest.iloc[0]:.2f}")
                add("AROlsCommon", f"{o17.r2_common.iloc[0]:.2f}")
            oA = infl[(infl.dataset == "A") & (infl.model == "ols")]
            if ds == "A" and len(oA):
                add("AOlsHonest", f"{oA.r2_honest.iloc[0]:.2f}")
                add("AOlsCommon", f"{oA.r2_common.iloc[0]:.2f}")
            pers = infl[(infl.dataset == ds) & (infl.model == "persistence")]
            if len(pers):
                add(f"{tag}PersD", f"{pers.delta.iloc[0]*100:+.0f}")

    # tau
    p = OUT / "analysis_ranking.csv"
    if p.exists():
        rk = pd.read_csv(p)
        for ds, tag in [("C0", "CO"), ("A", "A"), ("B", "B"), ("A17", "AR")]:
            sub = rk[(rk.dataset == ds) & (rk.comparison == "honest_vs_common")]
            if len(sub):
                add(f"{tag}Tau", f"{sub.tau.iloc[0]:.2f}")
                add(f"{tag}TauLo", f"{sub.tau_lo.iloc[0]:.2f}")
                add(f"{tag}TauHi", f"{sub.tau_hi.iloc[0]:.2f}")
                add(f"{tag}TauExclOne", "yes" if sub.ci_excludes_1.iloc[0] else "no")

    # persistence accounting
    p = OUT / "analysis_persistence.csv"
    if p.exists():
        pe = pd.read_csv(p)
        for ds, tag in [("C0", "CO"), ("A", "A"), ("B", "B"), ("A17", "AR")]:
            sub = pe[pe.dataset == ds]
            if not len(sub):
                continue
            row = sub.iloc[0]
            hs = [c for c in sub.columns if c.endswith("_beats_persistence_honest")]
            cs = [c for c in sub.columns if c.endswith("_beats_persistence_common")]
            nh = sum(int(row[c]) for c in hs)
            nc = sum(int(row[c]) for c in cs)
            add(f"{tag}BeatsPersHonest", f"{nh}/{len(hs)}")
            add(f"{tag}BeatsPersCommon", f"{nc}/{len(cs)}")

    # decision-stakes consequences (same target years, C0 & B)
    pp = OUT / "benchmark_predictions.parquet"
    if pp.exists():
        prx = pd.read_parquet(pp)
        def _g(ds, model, v, tm, s, pp_, years):
            m = prx[(prx.dataset == ds) & (prx.model == model) & (prx.validation == v)
                    & (prx.timing == tm) & (prx.preproc == pp_) & (prx.seed == 0)]
            m = m[m.subcomp == "on"] if s == "on" else m[m.subcomp != "on"]
            return m[m.year.isin(years)]
        Y5 = list(range(2020, 2025))
        leak = _g("C0", "ols", "loocv", "contemporaneous", "on", "global", Y5)
        persC = _g("C0", "persistence", "rolling_origin", "lagged", "off", "fold", Y5)
        xgbC = _g("C0", "xgb", "rolling_origin", "lagged", "off", "fold", Y5)
        if len(leak) and len(persC):
            mae = lambda d: float((d.y_true - d.y_pred).abs().mean())
            add("ConsLeakMAE", f"{mae(leak):,.0f}")
            add("ConsLeakPct", f"{100*mae(leak)/leak.y_true.mean():.1f}")
            add("ConsPersMAE", f"{mae(persC):,.0f}")
            add("ConsPersPct", f"{100*mae(persC)/persC.y_true.mean():.1f}")
            add("ConsXgbMAE", f"{mae(xgbC):,.0f}")
            add("ConsXgbPct", f"{100*mae(xgbC)/xgbC.y_true.mean():.1f}")
            add("ConsFactor", f"{mae(xgbC)/mae(leak):.0f}")
        YB = list(range(2020, 2024))
        leakB = _g("B", "xgb", "loocv", "contemporaneous", "on", "global", YB)
        persB = _g("B", "persistence", "rolling_origin", "lagged", "off", "fold", YB)
        if len(leakB):
            mae = lambda d: float((d.y_true - d.y_pred).abs().mean())
            add("ConsBLeakPct", f"{100*mae(leakB)/leakB.y_true.mean():.1f}")
            add("ConsBPersPct", f"{100*mae(persB)/persB.y_true.mean():.1f}")

    # tuned-station comparison: among {rf, xgb, rf_tuned, xgb_tuned}
    pt = OUT / "analysis_tuned.csv"
    if pt.exists() and pp.exists():
        tn = pd.read_csv(pt)
        prx = pd.read_parquet(pp)
        ST_MAIN = {("C0", "honest"): ("rolling_origin", "lagged", "off", "fold"),
                   ("C0", "common"): ("loocv", "contemporaneous", "on", "global"),
                   ("A", "honest"): ("rolling_origin", "lagged", "off", "fold"),
                   ("A", "common"): ("loocv", "contemporaneous", "off", "global"),
                   ("A17", "honest"): ("rolling_origin", "lagged", "off", "fold"),
                   ("A17", "common"): ("loocv", "contemporaneous", "off", "global"),
                   ("B", "honest"): ("rolling_origin", "lagged", "off", "fold"),
                   ("B", "common"): ("loocv", "contemporaneous", "on", "global")}
        for ds, tag in [("C0", "CO"), ("A", "A"), ("A17", "AR"), ("B", "B")]:
            for st, stt in [("honest", "Honest"), ("common", "Common")]:
                sub = tn[(tn.dataset == ds) & (tn.station == st)]
                if len(sub) == 0:
                    continue
                rmse_p = float(sub[sub.model == "persistence"].rmse.iloc[0])
                v, tm, s, pp_ = ST_MAIN[(ds, st)]
                wins = 0
                for mdl in ("rf", "xgb"):
                    m = prx[(prx.dataset == ds) & (prx.model == mdl)
                            & (prx.validation == v) & (prx.timing == tm)
                            & (prx.preproc == pp_) & (prx.seed == 0)]
                    m = m[m.subcomp == "on"] if s == "on" else m[m.subcomp != "on"]
                    if len(m):
                        wins += int(float((m.y_true - m.y_pred).pow(2).mean() ** 0.5) < rmse_p)
                for mdl in ("rf_tuned", "xgb_tuned"):
                    m = sub[sub.model == mdl]
                    if len(m):
                        wins += int(float(m.rmse.iloc[0]) < rmse_p)
                add(f"Tuned{tag}{stt}", f"{wins}/4")

    # mechanism analysis (fig5)
    pm_ = OUT / "analysis_mechanism.csv"
    if pm_.exists():
        import numpy as _np
        from scipy.stats import pearsonr as _pr
        d_ = pd.read_csv(pm_).dropna()
        r_, p_ = _pr(d_.n_years, d_.log_gain)
        r2_, p2_ = _pr(d_.trend_r2, d_.log_gain)
        add("nMechN", len(d_))
        add("nMechR", f"{r_:.2f}")
        add("nMechP", f"{p_:.3f}")
        add("nMechRTr", f"{r2_:.2f}")
        add("nMechRTrP", f"{p2_:.2f}")

    # survey
    fs = [str(q) for q in (OUT / "protocol_survey.csv",
                           D1 / "data" / "protocol_survey.csv") if q.exists()]
    if fs:
        sv = pd.concat([pd.read_csv(f) for f in fs], ignore_index=True)
        sv = sv[sv.waste_domain.isin(["CDW", "MSW"])]
        add("SurvN", len(sv))
        tmp = sv[sv.temporal_data == "Y"]
        add("SurvTemporal", len(tmp))
        add("SurvPers", int((tmp.persistence_baseline == "yes").sum()))
        chron = sv.validation_design.isin(["rolling_origin", "holdout_last_period"]).sum()
        add("SurvChron", int(chron))
        add("SurvChronPct", f"{100*chron/len(sv):.0f}\\%")
        leaky = int((sv.leakage_risk == "yes").sum())
        add("SurvLeak", leaky)
        loocv = int((sv.validation_design == "loocv").sum())
        rk5 = int((sv.validation_design == "random_kfold").sum())
        insample = int((sv.validation_design == "in_sample_fit_only").sum())
        unclear = int((sv.validation_design == "unclear").sum())
        holdrand = int((sv.validation_design == "holdout_random").sum())
        add("SurvLoocv", loocv)
        add("SurvRkF", rk5)
        add("SurvInsample", insample)
        add("SurvUnclear", unclear)
        add("SurvUnclearPct", f"{100*unclear/len(sv):.0f}\\%")
        add("SurvHoldoutRandom", holdrand)
        add("SurvUnclearLeak", int((sv.leakage_risk == "unclear").sum()))
        unct = int((sv.uncertainty_reported == "yes").sum())
        add("SurvUncertainty", unct)
        cdw_n = int((sv.waste_domain == "CDW").sum())
        add("SurvCdwN", cdw_n)
        add("SurvNoDoi", int((sv.doi.astype(str).str.strip() == "no-doi").sum()))
        det = sv[sv.validation_design != "unclear"]
        add("SurvDeterminable", len(det))
        add("SurvNonChron", int((det.validation_design != "holdout_last_period").sum()
                                - (det.validation_design == "rolling_origin").sum()
                                - (det.validation_design == "none_reported").sum()))
        add("SurvChronDet", int(det.validation_design.isin(
            ["holdout_last_period", "rolling_origin"]).sum()))
        rel = OUT / "reliability_agreement.csv"
        if not rel.exists():
            rel = D1 / "data" / "reliability_agreement.csv"
        if rel.exists():
            ra = pd.read_csv(rel)
            def _agr(f):
                vc = ra[f].value_counts(normalize=True)
                return (vc.get("agree", 0) + vc.get("both_unclear", 0)) * 100
            add("RelDomain", f"{_agr('waste_domain'):.0f}")
            add("RelTemporal", f"{_agr('temporal_data'):.0f}")
            add("RelValid", f"{_agr('validation_design'):.0f}")
            add("RelLeak", f"{_agr('leakage_risk'):.0f}")
            add("RelUncert", f"{_agr('uncertainty_reported'):.0f}")
        add("SurvMswN", int((sv.waste_domain == "MSW").sum()))

    # write macros: to manuscript/ when present (paper build), else output/
    has_ms = (MS / "main.tex").exists()
    if has_ms:
        MS.mkdir(exist_ok=True)
        target = MS / "numbers.tex"
    else:
        OUT.mkdir(exist_ok=True)
        target = OUT / "numbers.tex"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # safety (manuscript build only): define any generated-style \macro used
    # in main.tex but not yet computed as "--", so LaTeX always compiles
    if has_ms:
        import re
        main = (MS / "main.tex").read_text(encoding="utf-8")
        used = set(re.findall(r"\\((?:Surv|CO|A|B|hl|n[A-Z])\w{2,})", main))
        known = set()
        for ln in lines:
            m = re.match(r"\\newcommand\{\\(\w+)\}", ln)
            if m:
                known.add(m.group(1))
        missing = sorted(m for m in used if m not in known)
        if missing:
            with open(target, "a", encoding="utf-8") as f:
                for m in missing:
                    f.write(f"\\newcommand{{\\{m}}}{{--}}\n")
            print("PLACEHOLDER macros defined:", missing)
    print("\n".join(lines[:10]) + "\n...")
    print(f"wrote {target} ({len(lines)} macros)")


if __name__ == "__main__":
    main()
